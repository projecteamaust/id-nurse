-- ID Nurse database schema for PostgreSQL.
-- Run once on an empty database:   psql -d id_nurse -f schema.sql
-- Then add the demo data from the backend/ folder:   python -m app.seed
-- These tables match backend/app/models.py (tests/test_schema.py checks that they stay the same).
-- All times are TIMESTAMPTZ; the API shows them in the server's local time.

BEGIN;

-- Staff. Nurses sign in with their employee ID only (password_hash is NULL); supervisors need a password.
CREATE TABLE users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   VARCHAR(20)  NOT NULL UNIQUE,
    name          VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255),                       -- PBKDF2, never plain text
    role          VARCHAR(20)  NOT NULL,
    ward          VARCHAR(100) NOT NULL,
    CONSTRAINT users_role_check CHECK (role IN ('nurse', 'supervisor')),
    CONSTRAINT users_password_check CHECK (role = 'nurse' OR password_hash IS NOT NULL)
);

-- Patients. The API returns age, calculated from date_of_birth.
CREATE TABLE patients (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_number    VARCHAR(20)  NOT NULL UNIQUE,
    name           VARCHAR(100) NOT NULL,
    date_of_birth  DATE         NOT NULL,
    room           VARCHAR(20)  NOT NULL,
    diagnosis_code VARCHAR(20)  NOT NULL               -- ICD-10, reserved for future AI
);

-- Supplies. Each one sits in one numbered drawer (slot_number) at one place in the cabinet.
-- cabinet_row 1 = row A (top), cabinet_column 1 = left; the API shows it as cabinet_location "A1".
CREATE TABLE items (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    sku            VARCHAR(30)  NOT NULL UNIQUE,
    category       VARCHAR(50)  NOT NULL,
    slot_number    INTEGER      NOT NULL UNIQUE,
    cabinet_row    INTEGER      NOT NULL,
    cabinet_column INTEGER      NOT NULL,
    quantity       INTEGER      NOT NULL,
    min_quantity   INTEGER      NOT NULL,
    CONSTRAINT items_cabinet_position_key UNIQUE (cabinet_row, cabinet_column),
    CONSTRAINT items_quantity_check CHECK (quantity >= 0),
    CONSTRAINT items_min_quantity_check CHECK (min_quantity >= 0),
    CONSTRAINT items_cabinet_position_check CHECK (cabinet_row >= 1 AND cabinet_column >= 1)
);

-- Orders: PENDING -> DISPENSING -> DONE | PARTIAL | FAILED, or CANCELLED before approval.
CREATE TABLE orders (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id   INTEGER     NOT NULL REFERENCES patients (id),
    nurse_id     INTEGER     NOT NULL REFERENCES users (id),
    status       VARCHAR(20) NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL,
    approved_at  TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    CONSTRAINT orders_status_check
        CHECK (status IN ('PENDING', 'DISPENSING', 'DONE', 'PARTIAL', 'FAILED', 'CANCELLED'))
);
CREATE INDEX ix_orders_created_at ON orders (created_at);
CREATE INDEX ix_orders_nurse_id ON orders (nurse_id);

-- Order lines. qty_dispensed goes up only after a successful pick.
CREATE TABLE order_items (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      INTEGER NOT NULL REFERENCES orders (id),
    item_id       INTEGER NOT NULL REFERENCES items (id),
    qty_requested INTEGER NOT NULL,
    qty_dispensed INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT order_items_qty_requested_check CHECK (qty_requested > 0),
    CONSTRAINT order_items_qty_dispensed_check CHECK (qty_dispensed >= 0 AND qty_dispensed <= qty_requested)
);
CREATE INDEX ix_order_items_order_id ON order_items (order_id);

-- The robot arm's work queue: one command per approved order.
-- path = the ordered stops (home -> drawers sorted by cabinet location -> pickup window -> home).
CREATE TABLE dispense_commands (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    INTEGER     NOT NULL UNIQUE REFERENCES orders (id),
    status      VARCHAR(20) NOT NULL,
    path        JSONB       NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL,
    started_at  TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    error       TEXT,
    CONSTRAINT dispense_commands_status_check
        CHECK (status IN ('pending', 'in_progress', 'completed', 'failed'))
);

-- Saved arm angles (calibration). Names: home, box, window, approach_slotN, grab_slotN.
CREATE TABLE poses (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_number INTEGER,
    pose_name   VARCHAR(50) NOT NULL UNIQUE,
    angles      JSONB       NOT NULL                   -- 6 values; the last one is the gripper
);

-- Every important action. Rows are only added, never changed or deleted.
-- actor_id NULL = the system (the robot). Problem reports are stored here too.
CREATE TABLE audit_log (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMPTZ NOT NULL,
    actor_id  INTEGER     REFERENCES users (id),
    action    VARCHAR(40) NOT NULL,
    order_id  INTEGER     REFERENCES orders (id),
    summary   TEXT        NOT NULL,
    details   JSONB       NOT NULL DEFAULT '{}'
);
CREATE INDEX ix_audit_log_timestamp ON audit_log (timestamp);
CREATE INDEX ix_audit_log_order_id ON audit_log (order_id);

COMMIT;
